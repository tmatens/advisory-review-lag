#!/usr/bin/env python3
"""Exploratory cuts of the dataset, printed as Markdown.

These are reference analyses, kept so the numbers can be reproduced.
They are not all used in any write-up, and several are weak or
confounded. Read the caveat under each table.

Waits are days from the maintainer publishing the repository advisory
to GitHub's review. "Surge cohort" means advisories published from May
to September 2026.
"""
import json
import math
import statistics
from collections import Counter, defaultdict
from pathlib import Path

from analyze import days, parse, pct

DATA = Path(__file__).parent / "data"
SURGE = ("2026-05", "2026-09")


def stats(xs):
    xs = sorted(x for x in xs if x is not None)
    if not xs:
        return "| 0 | | | | |"
    return (f"| {len(xs)} | {statistics.median(xs):.1f} | {pct(xs, .75):.1f} "
            f"| {100 * sum(x <= 7 for x in xs) / len(xs):.0f}% | {100 * sum(x > 30 for x in xs) / len(xs):.0f}% |")


HEAD = "| {} | n | median | p75 | within 7 days | over 30 days |\n|---|---|---|---|---|---|"


def table(title, note, label, groups):
    print(f"\n## {title}\n\n{note}\n\n" + HEAD.format(label))
    for name, xs in groups:
        print(f"| {name} " + stats(xs))


def spearman(x, y):
    def ranks(v):
        order = sorted(range(len(v)), key=lambda i: v[i])
        out, i = [0.0] * len(v), 0
        while i < len(order):
            j = i
            while j + 1 < len(order) and v[order[j + 1]] == v[order[i]]:
                j += 1
            for k in range(i, j + 1):
                out[order[k]] = (i + j) / 2
            i = j + 1
        return out
    a, b = ranks(x), ranks(y)
    ma, mb = statistics.mean(a), statistics.mean(b)
    return sum((p - ma) * (q - mb) for p, q in zip(a, b)) / math.sqrt(
        sum((p - ma) ** 2 for p in a) * sum((q - mb) ** 2 for q in b))


def main():
    advs = [json.loads(line) for line in (DATA / "advisories.jsonl").read_text().splitlines()]
    meta = {}
    if (DATA / "repo_meta.jsonl").exists():
        meta = {r["source"]: r for r in map(json.loads, (DATA / "repo_meta.jsonl").read_text().splitlines())}
    repo = [a for a in advs if a["repo_published"]]
    for a in repo:
        a["B"] = days(a["repo_published"], a["reviewed"])
        a["pub_month"] = a["repo_published"][:7]
        a["meta"] = meta.get((a["source"] or "").rstrip("/").lower())
    surge = [a for a in repo if SURGE[0] <= a["pub_month"] <= SURGE[1]]
    early = [a for a in repo if "2025-08" <= a["pub_month"] <= "2026-04"]
    coll = json.loads((DATA / "collection.json").read_text())
    print(f"# Exploratory analysis\n\nGenerated by `explore.py` from the snapshot collected {coll['collected_at']}. "
          "Reference only: see the caveat under each table.")

    print("\n## Queue depth\n\nAdvisories published by a maintainer and not yet reviewed, on the first of each month. "
          "Only advisories reviewed by the collection date are counted, so recent months are undercounts.\n\n"
          "| first of | waiting |\n|---|---|")
    months = sorted({a["reviewed"][:7] for a in repo})
    for m in months[1:]:
        first = m + "-01"
        print(f"| {m} | {sum(a['repo_published'] < first <= a['reviewed'] for a in repo)} |")

    print("\n## Share of each month's reviews published that same month\n\nA low share means review was mostly "
          "working through older advisories.\n\n| review month | reviews | same month |\n|---|---|---|")
    by_review = defaultdict(list)
    for a in repo:
        by_review[a["reviewed"][:7]].append(a["pub_month"] == a["reviewed"][:7])
    for m in sorted(by_review):
        print(f"| {m} | {len(by_review[m])} | {100 * sum(by_review[m]) / len(by_review[m]):.0f}% |")

    sev = ("critical", "high", "medium", "low")
    table("Severity, published August 2025 to April 2026", "Severity is the published rating.", "severity",
          [(s, [a["B"] for a in early if a["severity"] == s]) for s in sev])
    table("Severity, surge cohort", "Only reviewed advisories are visible. Severity could still decide which "
          "advisories are reviewed at all.", "severity", [(s, [a["B"] for a in surge if a["severity"] == s]) for s in sev])

    print("\n## Median wait by publication month and severity\n\nRecent months only include advisories already "
          "reviewed.\n\n| published | " + " | ".join(sev) + " |\n|---|---|---|---|---|")
    for m in sorted({a["pub_month"] for a in repo if a["pub_month"] >= "2026-03"}):
        cells = []
        for s in sev:
            xs = [a["B"] for a in repo if a["pub_month"] == m and a["severity"] == s]
            cells.append(f"{statistics.median(xs):.1f} ({len(xs)})" if xs else "")
        print(f"| {m} | " + " | ".join(cells) + " |")

    table("Ecosystem, surge cohort", "First listed package of each advisory.", "ecosystem",
          [(e, xs) for e, xs in sorted(
              ((e, [a["B"] for a in surge if a["packages"] and a["packages"][0]["eco"] == e])
               for e in {a["packages"][0]["eco"] for a in surge if a["packages"]}),
              key=lambda t: -len(t[1])) if len(xs) >= 30])

    counts = Counter((a["source"] or "").lower() for a in surge)
    table("Advisories from the same repository, surge cohort",
          "A rough stand-in for project activity. Confounded with project size.", "advisories in cohort",
          [(name, [a["B"] for a in surge if lo <= counts[(a["source"] or "").lower()] < hi])
           for name, lo, hi in (("1", 1, 2), ("2 to 5", 2, 6), ("6 to 20", 6, 21), ("21 or more", 21, 10 ** 9))])

    withmeta = [a for a in surge if a["meta"]]
    if withmeta:
        note = ("Stars, forks and watchers are counts at collection time, not when the advisory was published. "
                "Stars measure attention, not usage.")
        table("Stars, surge cohort", note, "stars",
              [(name, [a["B"] for a in withmeta if lo <= a["meta"]["stargazers_count"] < hi])
               for name, lo, hi in (("under 100", 0, 100), ("100 to 999", 100, 1000), ("1,000 to 9,999", 1000, 10000),
                                    ("10,000 to 49,999", 10000, 50000), ("50,000 and up", 50000, 10 ** 12))])
        for a in withmeta:
            a["age"] = days(a["meta"]["created_at"], a["repo_published"]) / 365.25
        table("Repository age at publication, surge cohort", "Age of the repository, not of the project.", "age",
              [(name, [a["B"] for a in withmeta if lo <= a["age"] < hi])
               for name, lo, hi in (("under 1 year", -99, 1), ("1 to 3 years", 1, 3), ("3 to 7 years", 3, 7), ("7 years and up", 7, 999))])
        table("Owner type, surge cohort", "GitHub account type of the repository owner.", "owner",
              [(o, [a["B"] for a in withmeta if a["meta"]["owner_type"] == o]) for o in ("Organization", "User")])
        print("\n## Rank correlation with wait, surge cohort\n\nSpearman. Values near zero mean little relationship.\n\n"
              "| measure | correlation |\n|---|---|")
        waits = [a["B"] for a in withmeta]
        for name, key in (("stars", "stargazers_count"), ("forks", "forks_count"), ("watchers", "subscribers_count")):
            print(f"| {name} | {spearman([a['meta'][key] for a in withmeta], waits):.3f} |")
        print(f"| repository age | {spearman([a['age'] for a in withmeta], waits):.3f} |")
        print(f"| advisories from the same repository | "
              f"{spearman([counts[(a['source'] or '').lower()] for a in withmeta], waits):.3f} |")

    # How a month looked shortly after it ended, against how it looks now. Shows why the
    # most recent months cannot be read yet: slow reviews are missing until they happen.
    from datetime import datetime as _dt, timedelta as _td, timezone as _tz
    released = []
    for a in repo:
        rels = [p["release"] for p in a["packages"] if p.get("release")]
        if rels:
            first = min(rels, key=parse)
            wait = days(first, a["reviewed"])
            if wait is not None and wait >= 0:
                released.append((first, a["reviewed"], wait))
    print("\n## Each release month as it looked soon after it ended\n\nMedian days from fix release to review, "
          "counting only advisories reviewed by the stated point. Recent months are shown in the main report "
          "at roughly these ages.\n\n| release month | 11 days after month end | | 41 days after month end | | at collection | |\n"
          "|---|---|---|---|---|---|---|\n| | advisories | median | advisories | median | advisories | median |")
    collected = coll["collected_at"]
    for m in sorted({r[0][:7] for r in released if r[0][:7] >= "2026-01"}):
        year, month = int(m[:4]), int(m[5:])
        end = _dt(year + (month == 12), month % 12 + 1, 1, tzinfo=_tz.utc)
        cells = []
        for offset in (10, 40):
            as_of = (end + _td(days=offset)).isoformat()
            if as_of > collected:
                cells += ["", ""]
                continue
            seen = [r[2] for r in released if r[0][:7] == m and r[1] <= as_of]
            cells += [str(len(seen)), f"{statistics.median(seen):.1f}" if seen else ""]
        now = [r[2] for r in released if r[0][:7] == m]
        print(f"| {m} | " + " | ".join(cells) + f" | {len(now)} | {statistics.median(now):.1f} |")

    print("\n## Review activity by weekday\n\nAll reviewed advisories.\n\n| weekday | reviews |\n|---|---|")
    wd = Counter(parse(a["reviewed"]).strftime("%A") for a in advs)
    for d in ("Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"):
        print(f"| {d} | {wd[d]} |")


if __name__ == "__main__":
    main()
